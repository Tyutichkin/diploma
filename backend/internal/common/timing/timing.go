// Package timing хранит хелперы для проектного правила: длительности всегда
// округляются вверх до целой минуты. Применяй на границах ввода (внешний
// провайдер расстояний, клиентская матрица, startTimeUnix), чтобы дальше
// система оперировала только минутно-выровненными значениями и агрегаты не
// «текли» из-за скрытых секунд.
package timing

// RoundUpSecToMinute округляет секунды вверх до ближайшей кратной 60.
// Для значений <= 0 возвращает 0.
func RoundUpSecToMinute(sec int) int {
	if sec <= 0 {
		return 0
	}
	r := sec % 60
	if r == 0 {
		return sec
	}
	return sec + (60 - r)
}

// RoundUpUnixToMinute округляет unix-секунды вверх до ближайшей минуты.
// Для значений <= 0 возвращает аргумент без изменений (вызывающий сам решает,
// что подставить вместо «нулевого» времени).
func RoundUpUnixToMinute(unix int64) int64 {
	if unix <= 0 {
		return unix
	}
	r := unix % 60
	if r == 0 {
		return unix
	}
	return unix + (60 - r)
}
